#!/usr/bin/env python3
"""Summarize default-off HIP MoE dispatch traces in llama-cli stderr logs."""

import argparse
from collections import Counter
from pathlib import Path


PREFIX = "evox2_moe_dispatch_v1 "
FIELDS = ("seq", "layer", "role", "path", "N", "weight_type", "J")


def parse_records(lines):
    records = []
    truncated = False
    for line in lines:
        at = line.find(PREFIX)
        if at < 0:
            continue
        fields = {}
        for item in line[at + len(PREFIX):].split():
            if "=" in item:
                key, value = item.split("=", 1)
                fields[key] = value
        if "truncated_after" in fields:
            truncated = True
            continue
        if not all(key in fields for key in FIELDS):
            continue
        try:
            for name in ("seq", "layer", "N", "J"):
                fields[name] = int(fields[name])
        except ValueError:
            continue
        records.append(fields)
    return records, truncated


def aggregate(records):
    return Counter(
        (row["layer"], row["role"], row["weight_type"], row["path"], row["N"], row["J"])
        for row in records
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("stderr", type=Path, help="stderr.log generated by Measure-LlamaCli")
    ap.add_argument("--layer", type=int, help="Keep only one transformer layer")
    ap.add_argument("--n", type=int, help="Keep only microbatches with this token count")
    ap.add_argument("--require-role", action="append", default=[],
                    choices=("gate", "up", "down", "gate_up"),
                    help="Fail if a requested routed expert role is absent")
    ap.add_argument("--strict", action="store_true", help="Fail if the trace reached its output cap")
    args = ap.parse_args()

    with args.stderr.open("r", encoding="utf-8-sig", errors="replace") as f:
        records, truncated = parse_records(f)

    if args.layer is not None:
        records = [row for row in records if row["layer"] == args.layer]
    if args.n is not None:
        records = [row for row in records if row["N"] == args.n]

    if not records:
        ap.error("No matching MoE dispatch rows. Check GGML_HIP_MOE_TRACE=1, layer/N filters and ROCm backend.")

    print("layer role    weight_type   path           N    J calls")
    for (layer, role, weight_type, path, n, j), count in sorted(aggregate(records).items()):
        print(f"{layer:5d} {role:7s} {weight_type:13s} {path:13s} {n:5d} {j:4d} {count:5d}")
    print(f"Total matching host dispatches: {len(records)}")
    if truncated:
        print("WARNING: trace reached GGML_HIP_MOE_TRACE_LIMIT; not all dispatches were captured.")

    actual = {row["role"] for row in records}
    missing = set(args.require_role) - actual
    if missing:
        ap.error("Missing expected routed expert roles: " + ", ".join(sorted(missing)))
    if truncated and args.strict:
        ap.error("Trace was truncated: increase GGML_HIP_MOE_TRACE_LIMIT or narrow the filters.")


if __name__ == "__main__":
    main()
